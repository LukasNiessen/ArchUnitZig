fn writeSummary(writer: *Writer, snapshot: *const GraphReportSnapshot) Writer.Error!void {
    try writer.writeAll("<section class=\"summary\" aria-label=\"Graph summary\">");
    try writeMetric(writer, snapshot.summary.node_count, "Nodes");
    try writeMetric(writer, snapshot.summary.edge_count, "Aggregated edges");
    try writeMetric(writer, snapshot.summary.raw_edge_count, "Raw edges");
    try writeMetric(writer, snapshot.summary.external_edge_count, "External edges");
    try writer.writeAll("</section>");
}

fn writeMetric(writer: *Writer, value: usize, label: []const u8) Writer.Error!void {
    try writer.print("<div class=\"metric\"><strong>{d}</strong>", .{value});
    try escaping.writeHtml(writer, label);
    try writer.writeAll("</div>");
}

fn writeNodes(writer: *Writer, snapshot: *const GraphReportSnapshot) Writer.Error!void {
    try writer.writeAll("<section><h2>Nodes</h2><table><thead><tr><th>ID</th><th>Label</th></tr></thead><tbody>");
    for (snapshot.nodes) |node| {
        try writer.writeAll("<tr><td><code>");
        try escaping.writeHtml(writer, node.id);
        try writer.writeAll("</code></td><td><code>");
        try escaping.writeHtml(writer, node.label);
        try writer.writeAll("</code></td></tr>");
    }
    try writer.writeAll("</tbody></table></section>");
}

fn writeDependencies(writer: *Writer, snapshot: *const GraphReportSnapshot) Writer.Error!void {
    try writer.writeAll("<section><h2>Dependencies</h2>");
    if (snapshot.edges.len == 0) {
        try writer.writeAll("<div class=\"empty\">No dependency edges matched this graph query.</div></section>");
        return;
    }
    try writer.writeAll(
        "<table><thead><tr><th>Source</th><th>Target</th><th>Count</th><th>External</th>" ++
            "<th>Import kinds</th><th>Target classes</th><th>Availability</th></tr></thead><tbody>",
    );
    for (snapshot.edges) |edge| {
        try writer.writeAll("<tr");
        if (edge.external or support.edgeIsResource(edge.target_classes)) {
            try writer.writeAll(" class=\"");
            if (edge.external) try writer.writeAll("external-edge");
            if (edge.external and support.edgeIsResource(edge.target_classes)) try writer.writeByte(' ');
            if (support.edgeIsResource(edge.target_classes)) try writer.writeAll("resource-edge");
            try writer.writeByte('"');
        }
        try writer.writeAll("><td><code>");
        try escaping.writeHtml(writer, edge.source);
        try writer.writeAll("</code></td><td><code>");
        try escaping.writeHtml(writer, edge.target);
        try writer.print("</code></td><td>{d}</td><td>{s}</td><td>", .{
            edge.count,
            if (edge.external) "yes" else "no",
        });
        try support.writeImportKinds(writer, edge.import_kinds, ", ");
        try writer.writeAll("</td><td>");
        try support.writeTargetClasses(writer, edge.target_classes, ", ");
        try writer.writeAll("</td><td>");
        try support.writeTargetAvailabilities(writer, edge.target_availabilities, ", ");
        try writer.writeAll("</td></tr>");
    }
    try writer.writeAll("</tbody></table></section>");
}

fn writeSource(writer: *Writer, name: []const u8, source: []const u8) Writer.Error!void {
    try writer.writeAll("<details><summary>");
    try escaping.writeHtml(writer, name);
    try writer.writeAll("</summary><pre>");
    try escaping.writeHtml(writer, source);
    try writer.writeAll("</pre></details>");
}

test "HTML renderer is one offline escaped document with complete metadata and sources" {
    var snapshot = try @import("test_snapshot.zig").make(std.testing.allocator);
    defer snapshot.deinit(std.testing.allocator);
    const rendered = try toHtml(std.testing.allocator, &snapshot);
    defer std.testing.allocator.free(rendered);

    try std.testing.expect(std.mem.startsWith(u8, rendered, "<!DOCTYPE html><html lang=\"en\">"));
    try std.testing.expect(std.mem.endsWith(u8, rendered, "</body></html>"));
    try std.testing.expectEqual(@as(usize, 1), std.mem.count(u8, rendered, "<html"));
    try std.testing.expectEqual(@as(usize, 1), std.mem.count(u8, rendered, "</html>"));
    for ([_][]const u8{
        "<title>Architecture &lt;Main&gt;\r\n&quot;quoted&quot;</title>",
        "<strong>4</strong>Nodes",
        "app/&quot;api&quot;\n.zig",
        "domain&lt;&amp;&gt;.zig",
        "class=\"resource-edge\"",
        "class=\"external-edge\"",
        "embedded_file",
        "compiler",
        "unresolved",
        "<summary>Mermaid</summary>",
        "<summary>DOT</summary>",
        "<summary>D2</summary>",
        "<summary>JSON snapshot</summary>",
    }) |needle| try std.testing.expect(std.mem.indexOf(u8, rendered, needle) != null);
    try std.testing.expect(std.mem.indexOf(u8, rendered, "https://") == null);
    try std.testing.expect(std.mem.indexOf(u8, rendered, "http://") == null);
    try std.testing.expect(std.mem.indexOf(u8, rendered, "<script") == null);
    try std.testing.expect(std.mem.indexOf(u8, rendered, "<link") == null);
}

test "empty HTML snapshot renders an explicit empty dependency state" {
    const empty_nodes = try std.testing.allocator.alloc(report.GraphReportNode, 0);
    const empty_edges = try std.testing.allocator.alloc(report.GraphReportEdge, 0);
    var snapshot = report.GraphReportSnapshot{
        .title = try std.testing.allocator.dupe(u8, "Empty"),
        .nodes = empty_nodes,
        .edges = empty_edges,
        .summary = .{ .node_count = 0, .edge_count = 0, .raw_edge_count = 0, .external_edge_count = 0 },
    };
    defer snapshot.deinit(std.testing.allocator);
    const rendered = try toHtml(std.testing.allocator, &snapshot);
    defer std.testing.allocator.free(rendered);
    try std.testing.expect(std.mem.indexOf(
        u8,
        rendered,
        "No dependency edges matched this graph query.",
    ) != null);
}

fn exerciseAllocationFailures(allocator: Allocator, snapshot: *const GraphReportSnapshot) RenderError!void {
    const rendered = try toHtml(allocator, snapshot);
    defer allocator.free(rendered);
}

test "HTML rendering and nested source rendering clean up every allocation failure" {
    var snapshot = try @import("test_snapshot.zig").make(std.testing.allocator);
    defer snapshot.deinit(std.testing.allocator);
    try std.testing.checkAllAllocationFailures(
        std.testing.allocator,
        exerciseAllocationFailures,
        .{&snapshot},
    );
}
