const std = @import("std");

const escaping = @import("escaping.zig");
const json_renderer = @import("json_renderer.zig");
const report = @import("../projection/report.zig");
const support = @import("support.zig");
const text_renderers = @import("text_renderers.zig");

const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
pub const GraphReportSnapshot = report.GraphReportSnapshot;
pub const RenderError = text_renderers.RenderError;

pub fn toHtml(allocator: Allocator, snapshot: *const GraphReportSnapshot) RenderError![]u8 {
    const dot = try text_renderers.toDot(allocator, snapshot);
    defer allocator.free(dot);
    const mermaid = try text_renderers.toMermaid(allocator, snapshot);
    defer allocator.free(mermaid);
    const d2 = try text_renderers.toD2(allocator, snapshot);
    defer allocator.free(d2);
    const json = try json_renderer.toJson(allocator, snapshot);
    defer allocator.free(json);

    var output: Writer.Allocating = .init(allocator);
    errdefer output.deinit();
    const writer = &output.writer;
    writer.writeAll(document_head) catch return error.OutOfMemory;
    escaping.writeHtml(writer, snapshot.title) catch return error.OutOfMemory;
    writer.writeAll("</title></head><body><header><h1>") catch return error.OutOfMemory;
    escaping.writeHtml(writer, snapshot.title) catch return error.OutOfMemory;
    writer.writeAll(
        "</h1><p>Generated by ArchUnitZig graph reporting</p></header><main>",
    ) catch return error.OutOfMemory;
    writeSummary(writer, snapshot) catch return error.OutOfMemory;
    writeNodes(writer, snapshot) catch return error.OutOfMemory;
    writeDependencies(writer, snapshot) catch return error.OutOfMemory;
    writer.writeAll("<section><h2>Portable sources</h2>") catch return error.OutOfMemory;
    writeSource(writer, "Mermaid", mermaid) catch return error.OutOfMemory;
    writeSource(writer, "DOT", dot) catch return error.OutOfMemory;
    writeSource(writer, "D2", d2) catch return error.OutOfMemory;
    writeSource(writer, "JSON snapshot", json) catch return error.OutOfMemory;
    writer.writeAll("</section></main></body></html>") catch return error.OutOfMemory;
    return output.toOwnedSlice();
}

